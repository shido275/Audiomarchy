#!/bin/bash
#
# Build the Music menu from menu.tsv + actions.tsv and merge it into
# ~/.config/omarchy/extensions/omarchy-menu.jsonc.
#
# Sourced by install.sh (which calls menu_build) or run directly, which is
# what `audiomarchy menu` does.

AUDIOMARCHY_INSTALL="${AUDIOMARCHY_INSTALL:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
export AUDIOMARCHY_INSTALL

source "$AUDIOMARCHY_INSTALL/helpers/ui.sh"
source "$AUDIOMARCHY_INSTALL/helpers/menu-merge.sh"

jesc() {
  local s=$1
  s=${s//\\/\\\\}
  s=${s//\"/\\\"}
  printf '%s' "$s"
}

pkg_bins() {
  pacman -Ql "$1" 2>/dev/null |
    awk '$2 ~ /^\/usr\/bin\/[^\/]+$/ { sub(/.*\//, "", $2); print $2 }' | sort -u
}

# Ask pacman what the package actually installed instead of guessing a
# binary name: exact match first, then a versioned name (ardour -> ardour9),
# then the shortest entry.
pick_bin() {
  local package=$1
  pkg_bins "$package" | awk -v p="$package" '
    { bin[NR] = $0 }
    END {
      if (NR == 0) exit
      for (i = 1; i <= NR; i++) if (bin[i] == p) { print bin[i]; exit }
      for (i = 1; i <= NR; i++) if (bin[i] ~ ("^" p "[0-9]+$")) { print bin[i]; exit }
      best = bin[1]
      for (i = 2; i <= NR; i++) if (length(bin[i]) < length(best)) best = bin[i]
      print best
    }'
}

# First LV2/VST3/CLAP bundle directory the package installed.
pkg_plugin_dir() {
  local package=$1 dir
  dir=$(pacman -Ql "$package" 2>/dev/null | awk -F/ '
    $2 == "usr" && $3 == "lib" && ($4 == "lv2" || $4 == "vst3" || $4 == "clap") {
      print "/" $2 "/" $3 "/" $4 "/" $5
      exit
    }')
  if [[ -n $dir && -d $dir ]]; then
    printf '%s\n' "$dir"
  fi
  return 0
}

menu_build() {
  local menu_jsonc="${XDG_CONFIG_HOME:-$HOME/.config}/omarchy/extensions/omarchy-menu.jsonc"
  local rows="$AUDIOMARCHY_INSTALL/music/menu.tsv"
  local actions="$AUDIOMARCHY_INSTALL/music/actions.tsv"
  local block block_check
  local -A category_icon
  local submenus=(
    "music|F001|Music"
    "music.daws|F144|DAWs"
    "music.instruments|F11C|Instruments"
    "music.effects|F1DE|Effects"
    "music.routing|F1E6|Routing"
    "music.mastering|F0AD|Mastering"
    "music.live|F028|Live & DJ"
    "music.notation|F1C7|Notation"
    "music.tools|F0E7|Tools"
  )
  local row id hex label short entry category package mode extra icon action bin dir
  local section checked full

  block=$(mktemp) || return 1
  block_check=$(mktemp) || return 1

  {
    echo '  // BEGIN audiomarchy music menu (generated by install/music/menu.sh — edit install/music/menu.tsv instead of this block)'
    for row in "${submenus[@]}"; do
      IFS='|' read -r id hex label <<< "$row"
      icon=$(printf '%b' "\\u${hex}")
      short=${id#music.}
      [[ $short == "$id" ]] && short=root
      category_icon["$short"]="$icon"
      printf '  "%s": {"icon":"%s","label":"%s"},\n' \
        "$id" "$(jesc "$icon")" "$label"
    done

    # One row per app. A package that is not installed produces no entry:
    # the menu never points at something that is not there.
    while IFS=$'\t' read -r entry category label package mode extra; do
      [[ -z $entry || $entry == \#* ]] && continue
      icon=${category_icon[$category]:-}

      if ! pacman -Qq "$package" >/dev/null 2>&1; then
        continue
      fi

      case "$mode" in
        gui)
          bin=$(pick_bin "$package")
          [[ -z $bin ]] && { au_note "menu: no binary found for $package — skipped"; continue; }
          action="uwsm-app -- $bin"
          ;;
        tui)
          bin=$(pick_bin "$package")
          [[ -z $bin ]] && { au_note "menu: no binary found for $package — skipped"; continue; }
          action="omarchy-launch-tui bash -c '$bin; exec bash'"
          ;;
        plugin)
          dir=$(pkg_plugin_dir "$package")
          [[ -z $dir ]] && { au_note "menu: no plugin bundle found for $package — skipped"; continue; }
          action="uwsm-app -- xdg-open '$dir'"
          ;;
        action)
          action="$extra"
          ;;
        *)
          au_note "menu: unknown mode '$mode' for $entry — skipped"
          continue
          ;;
      esac

      printf '  "music.%s.%s": {"icon":"%s","label":"%s","action":"%s"},\n' \
        "$category" "$entry" "$(jesc "$icon")" "$(jesc "$label")" "$(jesc "$action")"
    done < "$rows"

    # Quick actions: Trigger > Music, and the same ones under Music > Tools.
    printf '  "trigger.music": {"icon":"%s","label":"Music"},\n' \
      "$(jesc "${category_icon[root]}")"
    while IFS=$'\t' read -r section entry label action checked; do
      [[ -z $section || $section == \#* ]] && continue
      full="$section.$entry"
      if [[ -n ${checked:-} && $checked != "-" ]]; then
        printf '  "%s": {"icon":"%s","label":"%s","action":"%s","checked":"%s"},\n' \
          "$full" "$(jesc "${category_icon[root]}")" "$(jesc "$label")" \
          "$(jesc "$action")" "$(jesc "$checked")"
      else
        printf '  "%s": {"icon":"%s","label":"%s","action":"%s"},\n' \
          "$full" "$(jesc "${category_icon[root]}")" "$(jesc "$label")" "$(jesc "$action")"
      fi
    done < "$actions"

    echo '  // END audiomarchy music menu'
  } > "$block"

  if au_dry; then
    {
      echo '{'
      cat "$block"
      echo '}'
    } > "$block_check"
    if au_menu_jsonc_valid "$block_check"; then
      au_ok "[dry-run] Music menu block is valid ($(wc -l < "$block") entries)"
    else
      au_fail "[dry-run] generated menu would not parse"
      rm -f "$block" "$block_check"
      return 1
    fi
    rm -f "$block" "$block_check"
    return 0
  fi

  mkdir -p "$(dirname "$menu_jsonc")"
  [[ -f $menu_jsonc ]] || printf '{\n}\n' > "$menu_jsonc"

  if ! au_merge_menu_block music "$block" "$menu_jsonc"; then
    au_fail "Music menu was not written"
    rm -f "$block" "$block_check"
    return 1
  fi

  rm -f "$block" "$block_check"
  au_ok "Music menu written to $menu_jsonc"
}

if [[ ${BASH_SOURCE[0]} == "$0" ]]; then
  menu_build
fi
